/** 문서 본문을 이루는 블록. 마크다운을 런타임에 파싱하지 않고 구조를 그대로 데이터로 갖는다. */
export type LegalBlock =
  /** 일반 문단. */
  | { kind: "paragraph"; text: string }
  /** 글머리 기호 목록. */
  | { kind: "bullets"; items: string[] }
  /** 조항 안의 소제목 + 설명 쌍(수집 항목·보유 기간·연락처처럼 라벨이 앞서는 블록). */
  | { kind: "fields"; rows: { label: string; value: string }[] };

export type LegalSection = {
  /** 조항 제목. 예: `제1조 (목적)`, `1. 수집하는 정보와 수집 방법` */
  heading: string;
  blocks: LegalBlock[];
};

export type LegalDocument = {
  title: string;
  /** 웹 원본의 시행일. 사본이 낡았는지 판별하는 기준값이다. */
  effectiveDate: string;
  /** 조항 앞에 오는 도입 문단. 없는 문서도 있다. */
  intro?: string;
  sections: LegalSection[];
};

